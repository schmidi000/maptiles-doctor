// Bundles the VS Code extension into a single CommonJS file. The extension
// host loads an extension by `main` with no npm install of workspace packages,
// so the entrypoint has to carry core and report with it. Unlike the action
// bundle this output is not committed: it is rebuilt when a .vsix is packaged.
import { copyFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const vscodeBundle = resolve(root, "packages/vscode/extension-dist/extension.cjs");

export async function bundleVscode() {
  // vsce refuses to package an extension without a license file, and the
  // repository keeps a single copy at the root.
  await copyFile(resolve(root, "LICENSE"), resolve(root, "packages/vscode/LICENSE"));

  await build({
    entryPoints: [resolve(root, "packages/vscode/src/extension.ts")],
    outfile: vscodeBundle,
    bundle: true,
    platform: "node",
    format: "cjs",
    target: "node24",
    // `vscode` is provided by the editor at runtime and never resolvable from
    // node_modules; better-sqlite3 and playwright are loaded lazily by core and
    // degrade to incomplete checks when they are absent.
    external: ["vscode", "better-sqlite3", "playwright"],
    // jsonc-parser's CommonJS entry is a UMD wrapper that require()s its own
    // files at runtime, which a single-file bundle cannot satisfy. Its ESM
    // entry bundles cleanly.
    alias: { "jsonc-parser": "jsonc-parser/lib/esm/main.js" },
    // See scripts/bundle-action.mjs: the canary runner's `import.meta.url` is
    // empty in a CommonJS bundle, and canaries degrade to an incomplete check.
    logOverride: { "empty-import-meta": "silent" },
    banner: {
      js: "// Generated by scripts/bundle-vscode.mjs. Do not edit; run `npm run bundle:vscode`."
    },
    legalComments: "none",
    minify: false
  });
  return vscodeBundle;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  console.log(`Bundled ${await bundleVscode()}`);
}
