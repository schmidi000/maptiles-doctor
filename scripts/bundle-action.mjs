// Bundles the GitHub Action into a single self-contained file. A runner checks
// out the repository and executes the bundle directly, with no npm install, so
// the output has to be committed and kept in sync with the sources.
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const actionBundle = resolve(root, "packages/action/action-dist/index.cjs");

export async function bundleAction() {
  await build({
    entryPoints: [resolve(root, "packages/action/src/main.ts")],
    outfile: actionBundle,
    bundle: true,
    platform: "node",
    // CommonJS, because dependencies of @actions/core call require() at runtime
    // for Node builtins, which an ESM bundle cannot satisfy.
    format: "cjs",
    target: "node24",
    // better-sqlite3 is a native module and playwright ships a browser
    // downloader, so neither can be bundled. Core loads both lazily, so their
    // absence only costs MBTiles sources and visual canaries.
    external: ["better-sqlite3", "playwright"],
    // The canary runner resolves its browser assets through `import.meta.url`,
    // which a CommonJS bundle cannot provide. That is expected here: playwright
    // is external anyway, so canaries degrade to an incomplete check.
    logOverride: { "empty-import-meta": "silent" },
    banner: {
      js: "// Generated by scripts/bundle-action.mjs. Do not edit; run `npm run bundle:action`."
    },
    legalComments: "none",
    minify: false
  });
  return actionBundle;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  console.log(`Bundled ${await bundleAction()}`);
}
